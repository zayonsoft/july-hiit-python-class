"""
/ - division
// - floor division
% - modulus
** exponential
"""

num_1 = 45
num_2 = 73

add = num_1 + num_2
diff = abs(num_1 - num_2)
mult = num_1 * num_2
div = num_1 / num_2
rem = num_1 % num_2
flr_div = num_1 // num_2
exp = num_1**num_2

print(f"The sum is: {add}")
print(f"{num_1} + {num_2} =  {add}")
print(f"The difference between {num_1} & {num_2} = {diff}")
print(mult)
print(div)
print(rem)
print(flr_div)
print(exp)
